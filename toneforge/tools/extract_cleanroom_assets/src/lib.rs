fn read_varint(buf: &[u8], pos: &mut usize) -> Option<u64> {
    let mut result = 0u64;
    let mut shift = 0u32;
    while *pos < buf.len() {
        let byte = buf[*pos];
        *pos += 1;
        result |= ((byte & 0x7F) as u64) << shift;
        if (byte & 0x80) == 0 {
            return Some(result);
        }
        shift += 7;
        if shift >= 64 {
            return None;
        }
    }
    None
}

fn skip_pb_field<'a>(buf: &'a [u8], pos: &mut usize, wire_type: u64) -> Option<&'a [u8]> {
    match wire_type {
        0 => {
            let _ = read_varint(buf, pos)?;
            Some(&[])
        }
        1 => {
            if *pos + 8 > buf.len() {
                return None;
            }
            let s = &buf[*pos..*pos + 8];
            *pos += 8;
            Some(s)
        }
        2 => {
            let len = read_varint(buf, pos)? as usize;
            if *pos + len > buf.len() {
                return None;
            }
            let s = &buf[*pos..*pos + len];
            *pos += len;
            Some(s)
        }
        5 => {
            if *pos + 4 > buf.len() {
                return None;
            }
            let s = &buf[*pos..*pos + 4];
            *pos += 4;
            Some(s)
        }
        _ => None,
    }
}

fn onnx_elem_type_name(code: u64) -> String {
    match code {
        1 => "float32".to_string(),
        2 => "uint8".to_string(),
        3 => "int8".to_string(),
        4 => "uint16".to_string(),
        5 => "int16".to_string(),
        6 => "int32".to_string(),
        7 => "int64".to_string(),
        8 => "string".to_string(),
        9 => "bool".to_string(),
        10 => "float16".to_string(),
        11 => "float64".to_string(),
        12 => "uint32".to_string(),
        13 => "uint64".to_string(),
        14 => "complex64".to_string(),
        15 => "complex128".to_string(),
        16 => "bfloat16".to_string(),
        other => format!("dtype_{other}"),
    }
}

fn parse_onnx_dim(buf: &[u8]) -> String {
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        match (field_no, wire_type) {
            (1, 0) => {
                if let Some(v) = read_varint(buf, &mut pos) {
                    return (v as i64).to_string();
                }
            }
            (2, 2) => {
                if let Some(s) = skip_pb_field(buf, &mut pos, 2) {
                    return String::from_utf8_lossy(s).into_owned();
                }
            }
            _ => {
                let _ = skip_pb_field(buf, &mut pos, wire_type);
            }
        }
    }
    "?".to_string()
}

fn parse_onnx_shape(buf: &[u8]) -> Vec<String> {
    let mut dims = Vec::new();
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        if field_no == 1 && wire_type == 2 {
            if let Some(dim_bytes) = skip_pb_field(buf, &mut pos, 2) {
                dims.push(parse_onnx_dim(dim_bytes));
            }
        } else {
            let _ = skip_pb_field(buf, &mut pos, wire_type);
        }
    }
    dims
}

fn parse_onnx_tensor_type(buf: &[u8]) -> (String, Vec<String>) {
    let mut elem_type = "unknown".to_string();
    let mut shape = Vec::new();
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        match (field_no, wire_type) {
            (1, 0) => {
                if let Some(code) = read_varint(buf, &mut pos) {
                    elem_type = onnx_elem_type_name(code);
                }
            }
            (2, 2) => {
                if let Some(shape_bytes) = skip_pb_field(buf, &mut pos, 2) {
                    shape = parse_onnx_shape(shape_bytes);
                }
            }
            _ => {
                let _ = skip_pb_field(buf, &mut pos, wire_type);
            }
        }
    }
    (elem_type, shape)
}

fn parse_onnx_type_proto(buf: &[u8]) -> (String, Vec<String>) {
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        if field_no == 1 && wire_type == 2 {
            if let Some(tt_bytes) = skip_pb_field(buf, &mut pos, 2) {
                return parse_onnx_tensor_type(tt_bytes);
            }
        } else {
            let _ = skip_pb_field(buf, &mut pos, wire_type);
        }
    }
    ("unknown".to_string(), Vec::new())
}

fn parse_onnx_value_info(buf: &[u8]) -> OnnxTensorPort {
    let mut name = String::new();
    let mut elem_type = "unknown".to_string();
    let mut shape = Vec::new();
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        match (field_no, wire_type) {
            (1, 2) => {
                if let Some(s) = skip_pb_field(buf, &mut pos, 2) {
                    name = String::from_utf8_lossy(s).into_owned();
                }
            }
            (2, 2) => {
                if let Some(tp_bytes) = skip_pb_field(buf, &mut pos, 2) {
                    let (et, sh) = parse_onnx_type_proto(tp_bytes);
                    elem_type = et;
                    shape = sh;
                }
            }
            _ => {
                let _ = skip_pb_field(buf, &mut pos, wire_type);
            }
        }
    }
    OnnxTensorPort {
        name,
        elem_type,
        shape,
    }
}

fn parse_onnx_tensor_proto_name(buf: &[u8]) -> Option<String> {
    let mut pos = 0usize;
    while pos < buf.len() {
        let Some(tag) = read_varint(buf, &mut pos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        if field_no == 8 && wire_type == 2 {
            if let Some(s) = skip_pb_field(buf, &mut pos, 2) {
                return Some(String::from_utf8_lossy(s).into_owned());
            }
        } else {
            let _ = skip_pb_field(buf, &mut pos, wire_type)?;
        }
    }
    None
}

/// Parses an `.onnx` model binary into its exact graph input/output tensor signature.
pub fn parse_onnx_model_signature(relative_path: &str, bytes: &[u8]) -> Result<OnnxModelSignature, String> {
    let sha256 = sha256_hex(bytes);
    let mut ir_version = 0u64;
    let mut producer_name = String::new();
    let mut graph_bytes: Option<&[u8]> = None;

    let mut pos = 0usize;
    while pos < bytes.len() {
        let Some(tag) = read_varint(bytes, &mut pos) else {
            return Err(format!("Corrupt ONNX protobuf tag in {relative_path}"));
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        match (field_no, wire_type) {
            (1, 0) => {
                ir_version = read_varint(bytes, &mut pos).unwrap_or(0);
            }
            (2, 2) => {
                if let Some(s) = skip_pb_field(bytes, &mut pos, 2) {
                    producer_name = String::from_utf8_lossy(s).into_owned();
                }
            }
            (7, 2) => {
                graph_bytes = skip_pb_field(bytes, &mut pos, 2);
            }
            _ => {
                let _ = skip_pb_field(bytes, &mut pos, wire_type);
            }
        }
    }

    let gbuf = graph_bytes.ok_or_else(|| format!("Missing GraphProto in {relative_path}"))?;
    let mut graph_name = String::new();
    let mut raw_inputs = Vec::new();
    let mut outputs = Vec::new();
    let mut initializer_names = HashSet::new();
    let mut initializer_count = 0usize;

    let mut gpos = 0usize;
    while gpos < gbuf.len() {
        let Some(tag) = read_varint(gbuf, &mut gpos) else {
            break;
        };
        let (field_no, wire_type) = (tag >> 3, tag & 7);
        match (field_no, wire_type) {
            (2, 2) => {
                if let Some(s) = skip_pb_field(gbuf, &mut gpos, 2) {
                    graph_name = String::from_utf8_lossy(s).into_owned();
                }
            }
            (5, 2) => {
                if let Some(init_bytes) = skip_pb_field(gbuf, &mut gpos, 2) {
                    initializer_count += 1;
                    if let Some(n) = parse_onnx_tensor_proto_name(init_bytes) {
                        initializer_names.insert(n);
                    }
                }
            }
            (11, 2) => {
                if let Some(vi_bytes) = skip_pb_field(gbuf, &mut gpos, 2) {
                    raw_inputs.push(parse_onnx_value_info(vi_bytes));
                }
            }
            (12, 2) => {
                if let Some(vo_bytes) = skip_pb_field(gbuf, &mut gpos, 2) {
                    outputs.push(parse_onnx_value_info(vo_bytes));
                }
            }
            _ => {
                let _ = skip_pb_field(gbuf, &mut gpos, wire_type);
            }
        }
    }

    // Per ONNX IR spec, filter out legacy initializers listed in GraphProto.input
    let inputs: Vec<OnnxTensorPort> = raw_inputs
        .into_iter()
        .filter(|p| !initializer_names.contains(&p.name))
        .collect();

    Ok(OnnxModelSignature {
        relative_path: relative_path.replace('\\', "/"),
        size_bytes: bytes.len() as u64,
        sha256,
        ir_version,
        producer_name,
        graph_name,
        inputs,
        outputs,
        initializer_count,
    })
}

