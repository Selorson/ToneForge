/// Base offset of the `IZRESEMBED` archive inside `iZOzone12Core.dll` (`579,805,696` bytes),
/// immediately following the 20-byte UTF-16LE PE resource type marker `"IZRESEMBED"` at `0x068E5B70`.
pub const IZRESEMBED_MARKER_OFFSET: u64 = 0x068E_5B70;
pub const IZRESEMBED_TOC_OFFSET: u64 = 0x068E_5B84;
pub const IZRESEMBED_TOC_END_REL: usize = 0x0002_5AA0;
pub const IZRESEMBED_UTF16LE_MARKER: [u8; 20] = *b"I\0Z\0R\0E\0S\0E\0M\0B\0E\0D\0";

/// Single entry in the `IZRESEMBED` Table of Contents (`0x068E5B84..0x0690B624`).
