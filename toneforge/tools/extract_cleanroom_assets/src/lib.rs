//! Clean-Room Asset Extractor & Verifier for **ToneForge**.
//!
//! Parses and extracts assets from `f:\FL studio\extracted_targets\`:
//! 1. `iZOzone12Core.dll` `IZRESEMBED` Virtual Filesystem (`offset = 0x068E5B84`, `2,970` entries,
//!    including 12 `.onnx` BSRNN/Unlimiter models, 2 `.npz` CNN classifiers, and 23 `DSP/AutomatableParamList_*.txt`).
//! 2. `exciter-triode-*.dat` (`0x8BAD43FC` magic, `KState<3,2,2,KorenFunction>` 360x360 bilinear LUTs).
//! 3. `vocals-small_sanitized.npz`, `drums-small_sanitized.npz`, `bass-small_sanitized.npz` (2-layer GRU-512).
//! 4. `ffproq4/DigiPageTable.xml` (601 Pro-Q 4 parameters) & `soothe3/DigiPageTable.xml` (143 Soothe3 parameters).

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::fs::{self, File};
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::{Path, PathBuf};

/// Base offset of the `IZRESEMBED` archive inside `iZOzone12Core.dll` (`579,805,696` bytes),
/// immediately following the 20-byte UTF-16LE PE resource type marker `"IZRESEMBED"` at `0x068E5B70`.
pub const IZRESEMBED_MARKER_OFFSET: u64 = 0x068E_5B70;
pub const IZRESEMBED_TOC_OFFSET: u64 = 0x068E_5B84;
pub const IZRESEMBED_TOC_END_REL: usize = 0x0002_5AA0;
pub const IZRESEMBED_UTF16LE_MARKER: [u8; 20] = *b"I\0Z\0R\0E\0S\0E\0M\0B\0E\0D\0";

/// Single entry in the `IZRESEMBED` Table of Contents (`0x068E5B84..0x0690B624`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct IzResEmbedEntry {
    pub index: usize,
    pub virtual_path: String,
    pub rel_data_offset: u32,
    pub absolute_file_offset: u64,
    pub data_size: u32,
}

/// Summary manifest generated by the Clean-Room asset extractor.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct CleanRoomAssetManifest {
    pub izresembed_total_entries: usize,
    pub onnx_models_count: usize,
    pub npz_models_count: usize,
    pub param_lists_count: usize,
    pub triode_lut_verified: bool,
    pub triode_lut_sample_rate: f64,
    pub triode_lut_dc_offset: f64,
    pub triode_lut_grid_dims: [u32; 2],
    pub extracted_files: Vec<ExtractedAssetRecord>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ExtractedAssetRecord {
    pub category: String,
    pub relative_dest_path: String,
    pub size_bytes: u64,
    pub sha256_prefix: String,
}

/// Parses the raw `IZRESEMBED` TOC buffer (`0x00025AA0` bytes starting at `0x068E5B84`).
/// Each record is: `null_terminated_utf8_path || rel_data_offset (u32 LE) || data_size (u32 LE)`.
pub fn parse_izresembed_toc_bytes(toc_bytes: &[u8], base_file_offset: u64) -> Vec<IzResEmbedEntry> {
    let mut entries = Vec::with_capacity(3000);
    let mut cursor = 0usize;
    let limit = toc_bytes.len();

    while cursor < limit {
        // Padding zeros mark the end of the TOC region
        if toc_bytes[cursor] == 0 {
            break;
        }
        let mut nul_pos = cursor;
        while nul_pos < limit && toc_bytes[nul_pos] != 0 {
            nul_pos += 1;
        }
        if nul_pos + 9 > limit {
            break;
        }
        let path_str = String::from_utf8_lossy(&toc_bytes[cursor..nul_pos]).into_owned();
        let off_pos = nul_pos + 1;
        let rel_data_offset =
            u32::from_le_bytes(toc_bytes[off_pos..off_pos + 4].try_into().unwrap());
        let data_size =
            u32::from_le_bytes(toc_bytes[off_pos + 4..off_pos + 8].try_into().unwrap());

        entries.push(IzResEmbedEntry {
            index: entries.len(),
            virtual_path: path_str,
            rel_data_offset,
            absolute_file_offset: base_file_offset + (rel_data_offset as u64),
            data_size,
        });
        cursor = off_pos + 8;
    }

    entries
}

/// Reads and parses the `IZRESEMBED` TOC directly from `iZOzone12Core.dll`.
pub fn read_izresembed_toc_from_dll(dll_path: &Path) -> Result<Vec<IzResEmbedEntry>, String> {
    let mut file =
        File::open(dll_path).map_err(|e| format!("Failed to open {}: {e}", dll_path.display()))?;
    let mut marker = [0u8; 20];
    file.seek(SeekFrom::Start(IZRESEMBED_MARKER_OFFSET))
        .map_err(|e| e.to_string())?;
    file.read_exact(&mut marker).map_err(|e| e.to_string())?;
    if marker != IZRESEMBED_UTF16LE_MARKER {
        return Err(format!(
            "Invalid IZRESEMBED UTF-16LE marker at 0x{:X}: {:?}",
            IZRESEMBED_MARKER_OFFSET, marker
        ));
    }

    let mut toc_buf = vec![0u8; IZRESEMBED_TOC_END_REL];
    file.read_exact(&mut toc_buf).map_err(|e| e.to_string())?;
    Ok(parse_izresembed_toc_bytes(&toc_buf, IZRESEMBED_TOC_OFFSET))
}

/// Extracts a specific `IzResEmbedEntry` payload from `iZOzone12Core.dll` to `dest_path`
/// and returns its `ExtractedAssetRecord` with SHA-256 digest prefix.
pub fn extract_izresembed_entry(
    dll_file: &mut File,
    entry: &IzResEmbedEntry,
    category: &str,
    dest_root: &Path,
    relative_dest: &str,
) -> Result<ExtractedAssetRecord, String> {
    let full_dest: PathBuf = dest_root.join(relative_dest);
    if let Some(parent) = full_dest.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }

    dll_file
        .seek(SeekFrom::Start(entry.absolute_file_offset))
        .map_err(|e| e.to_string())?;
    let mut payload = vec![0u8; entry.data_size as usize];
    dll_file.read_exact(&mut payload).map_err(|e| e.to_string())?;

    let mut hasher = Sha256::new();
    hasher.update(&payload);
    let digest_hex = hex::encode(hasher.finalize());

    let mut out = File::create(&full_dest).map_err(|e| e.to_string())?;
    out.write_all(&payload).map_err(|e| e.to_string())?;

    Ok(ExtractedAssetRecord {
        category: category.to_string(),
        relative_dest_path: relative_dest.replace('\\', "/"),
        size_bytes: entry.data_size as u64,
        sha256_prefix: digest_hex[..16].to_string(),
    })
}

/// Runs the Clean-Room asset verification and extraction pipeline from `extracted_targets_dir`
/// into `toneforge_assets_dir`.
///
/// When `extract_realtime_binaries` is true, extracts the real-time BSRNN `.onnx` models
/// (`ozone12_mss4stem_bsrnn_xs_120ms_ep147.onnx`, `delimit_exp009_ep080_fixed2.onnx`),
/// `gparamsBN8.0.npz`, all 23 `AutomatableParamList_*.txt` files, and copies `exciter-triode-48000.000000.dat`.
pub fn run_cleanroom_extraction(
    extracted_targets_dir: &Path,
    toneforge_assets_dir: &Path,
    extract_realtime_binaries: bool,
) -> Result<CleanRoomAssetManifest, String> {
    fs::create_dir_all(toneforge_assets_dir.join("models/bsrnn_realtime"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("models/npz_gru_stems"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("models/uvr5_mdx23c"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("models/uvr5_htdemucs"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("models/uvr5_vr_aspp"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("models/assistant_cnn"))
        .map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("exciter_luts")).map_err(|e| e.to_string())?;
    fs::create_dir_all(toneforge_assets_dir.join("param_tables")).map_err(|e| e.to_string())?;

    let dll_path = extracted_targets_dir
        .join("ozone12")
        .join("megacore_component")
        .join("MEGACORE_WIN")
        .join("iZOzone12Core.dll");
    let toc_entries = read_izresembed_toc_from_dll(&dll_path)?;

    let onnx_models_count = toc_entries
        .iter()
        .filter(|e| e.virtual_path.ends_with(".onnx"))
        .count();
    let npz_models_count = toc_entries
        .iter()
        .filter(|e| e.virtual_path.ends_with(".npz"))
        .count();
    let param_lists_count = toc_entries
        .iter()
        .filter(|e| e.virtual_path.starts_with("DSP/AutomatableParamList_"))
        .count();

    let mut extracted_files = Vec::new();
    let mut dll_file = File::open(&dll_path).map_err(|e| e.to_string())?;

    // Always extract the 23 TSV parameter specification tables (`DSP/AutomatableParamList_*.txt`)
    for entry in &toc_entries {
        if entry.virtual_path.starts_with("DSP/AutomatableParamList_") {
            let file_name = entry.virtual_path.trim_start_matches("DSP/");
            let rel_dest = format!("param_tables/{file_name}");
            let rec = extract_izresembed_entry(
                &mut dll_file,
                entry,
                "ozone12_param_table",
                toneforge_assets_dir,
                &rel_dest,
            )?;
            extracted_files.push(rec);
        }
    }

    if extract_realtime_binaries {
        let priority_targets = [
            (
                "models/ozone12_mss4stem_bsrnn_xs_120ms_ep147.onnx",
                "bsrnn_realtime",
                "models/bsrnn_realtime/ozone12_mss4stem_bsrnn_xs_120ms_ep147.onnx",
            ),
            (
                "models/delimit_exp009_ep080_fixed2.onnx",
                "bsrnn_realtime",
                "models/bsrnn_realtime/delimit_exp009_ep080_fixed2.onnx",
            ),
            (
                "Referencing/DSP/gparamsBN8.0.npz",
                "assistant_cnn",
                "models/assistant_cnn/gparamsBN8.0.npz",
            ),
        ];
        for (vpath, cat, rel_dest) in priority_targets {
            if let Some(entry) = toc_entries.iter().find(|e| e.virtual_path == vpath) {
                let rec = extract_izresembed_entry(
                    &mut dll_file,
                    entry,
                    cat,
                    toneforge_assets_dir,
                    rel_dest,
                )?;
                extracted_files.push(rec);
            }
        }
    }

    // Verify and copy `exciter-triode-48000.000000.dat` (`0x8BAD43FC`)
    let triode_path = extracted_targets_dir
        .join("ozone12")
        .join("exciterCache_component")
        .join("ExciterCache")
        .join("Exciter Cache")
        .join("exciter-triode-48000.000000.dat");
    let triode_bytes = fs::read(&triode_path)
        .map_err(|e| format!("Failed to read {}: {e}", triode_path.display()))?;
    let lut = dsp_ozone12_mastering::DkTriodeLut::from_dat_bytes(&triode_bytes)
        .map_err(|e| e.to_string())?;

    if extract_realtime_binaries {
        let dest_lut = toneforge_assets_dir.join("exciter_luts/exciter-triode-48000.000000.dat");
        fs::write(&dest_lut, &triode_bytes).map_err(|e| e.to_string())?;
        let mut hasher = Sha256::new();
        hasher.update(&triode_bytes);
        let digest_hex = hex::encode(hasher.finalize());
        extracted_files.push(ExtractedAssetRecord {
            category: "dk_triode_lut".to_string(),
            relative_dest_path: "exciter_luts/exciter-triode-48000.000000.dat".to_string(),
            size_bytes: triode_bytes.len() as u64,
            sha256_prefix: digest_hex[..16].to_string(),
        });
    }

    let manifest = CleanRoomAssetManifest {
        izresembed_total_entries: toc_entries.len(),
        onnx_models_count,
        npz_models_count,
        param_lists_count,
        triode_lut_verified: true,
        triode_lut_sample_rate: lut.sample_rate,
        triode_lut_dc_offset: lut.dc_offset,
        triode_lut_grid_dims: lut.grid_dims,
        extracted_files,
    };

    let manifest_json = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    fs::write(
        toneforge_assets_dir.join("cleanroom_asset_manifest.json"),
        manifest_json,
    )
    .map_err(|e| e.to_string())?;

    Ok(manifest)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_izresembed_toc_synthetic_and_real() {
        let mut fake_toc = Vec::new();
        fake_toc.extend_from_slice(b"models/test.onnx\0");
        fake_toc.extend_from_slice(&0x25AA0u32.to_le_bytes());
        fake_toc.extend_from_slice(&1024u32.to_le_bytes());
        fake_toc.push(0); // end of TOC

        let parsed = parse_izresembed_toc_bytes(&fake_toc, IZRESEMBED_TOC_OFFSET);
        assert_eq!(parsed.len(), 1);
        assert_eq!(parsed[0].virtual_path, "models/test.onnx");
        assert_eq!(parsed[0].rel_data_offset, 0x25AA0);
        assert_eq!(parsed[0].data_size, 1024);

        let real_dll = Path::new(r"f:\FL studio\extracted_targets\ozone12\megacore_component\MEGACORE_WIN\iZOzone12Core.dll");
        if real_dll.exists() {
            let entries = read_izresembed_toc_from_dll(real_dll).unwrap();
            assert_eq!(entries.len(), 2970);
        }
    }
}

